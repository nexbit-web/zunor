function buildServiceFocus(active: ServiceKey): string {
  const rule = SERVICE_RULES[active]
  const label = SERVICES.find((s) => s.key === active)?.label ?? active
  return [
    `── ФОКУС ПОСЛУГИ: клієнт обрав «${label}». Веди діалог ЛИШЕ в цьому треку; питань про інші послуги (сміття/вікна/хімчистку, якщо не стосуються цієї) НЕ став. ──`,
    `ОБОВʼЯЗКОВІ поля саме для цієї послуги (крім premise/service/when): ${rule.required}`,
    `Що допомагає майстру з ціною (НЕ обовʼязкове; спершу пропонуй фото ЗАМІСТЬ питань; текстом лише те, чого фото не покаже, одним повідомленням): ${rule.price}`,
  ].join('\n')
}

export function buildSystemPrompt(
  city: string | null,
  activeService: ServiceKey | null,
): string {
  const lines = buildBaseLines(city)
  // Guard: невідомий ключ (не мало б статися) → деградуємо до бази, не падаємо.
  if (activeService && SERVICE_RULES[activeService]) {
    lines.push(buildServiceFocus(activeService))
  }
  lines.push(SECURITY_LINE) // ЗАВЖДИ last
  return lines.join('\n')
}
