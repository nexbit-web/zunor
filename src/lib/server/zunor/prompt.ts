function buildServiceFocus(active: ServiceKey): string {
  const rule = SERVICE_RULES[active]
  const label = SERVICES.find((s) => s.key === active)?.label ?? active
  return [
    `── ФОКУС ПОСЛУГИ: клієнт обрав «${label}». Веди діалог ЛИШЕ в цьому треку; питань про інші послуги (сміття/вікна/хімчистку, якщо не стосуються цієї) НЕ став. ──`,
    `ОБОВʼЯЗКОВІ поля саме для цієї послуги (крім premise/service/when): ${rule.required}`,
    `Що допомагає майстру з ціною (НЕ обовʼязкове; спершу пропонуй фото ЗАМІСТЬ питань; текстом лише те, чого фото не покаже, одним повідомленням): ${rule.price}`,
  ].join('\n')
}

/** Ліміт нотатки. 500 символів — вистачає на адресу, кота й режим дня,
 *  але замало, щоб переписати поведінку агента. */
export const AI_NOTE_MAX = 500

/**
 * Нотатка користувача → блок промпту.
 *
 * Це ДАНІ, а не інструкції. Три рівні захисту:
 *   1. Явна рамка з попередженням для моделі перед і після тексту.
 *   2. Розділювачі, яких немає в звичайному тексті.
 *   3. Обрізання до AI_NOTE_MAX і зняття символів розмітки, якими
 *      користувач міг би вдати системне повідомлення.
 */

export function buildSystemPrompt(
  city: string | null,
  activeService: ServiceKey | null,
  lang: 'ru' | 'uk',
  aiProfile: unknown = null,
): string {
  // Мова — НАЙПЕРШИЙ і НАЙОСТАННІШИЙ рядок промпту. Модель дрейфує в мову
  // оточення (інструкції українські), тому одного рядка в середині мало —
  // тримаємо мову на обох кінцях, куди увага моделі найсильніша.
  const langTop =
    lang === 'ru'
      ? 'ВАЖНО — ОТВЕЧАЙ ТОЛЬКО НА РУССКОМ. Клиент пишет по-русски, поэтому каждое твоё сообщение — на русском, от первого слова до последнего. Примеры твоего стиля: «Привет! Помогу оформить заявку. Что нужно убрать?», «Понял, квартира. Сколько комнат?», «Отлично, записал на завтра». Так звучит каждая реплика. По-украински пиши ТОЛЬКО title и description в инструменте.'
      : 'КРИТИЧНО — ВІДПОВІДАЙ ТІЛЬКИ УКРАЇНСЬКОЮ. Клієнт пише українською, тому кожне повідомлення — українською. Приклади стилю: «Привіт! Допоможу оформити заявку. Що прибираємо?», «Зрозумів, квартира. Скільки кімнат?».'
  const langBottom =
    lang === 'ru'
      ? 'НАПОМИНАНИЕ: весь ответ — на русском. Заметил за собой украинское слово — исправь на русское.'
      : 'НАГАДУВАННЯ: уся відповідь — УКРАЇНСЬКОЮ.'

  // Прибираємо старий плейсхолдер із базових рядків — мову тепер несуть
  // langTop/langBottom, дубль у середині лише розмиває сигнал.
  const baseLines = buildBaseLines(city).filter(
    (l) => !l.startsWith('__LANG__'),
  )
  const lines = [langTop, ...baseLines]
  // Guard: невідомий ключ (не мало б статися) → деградуємо до бази, не падаємо.
  if (activeService && SERVICE_RULES[activeService]) {
    lines.push(buildServiceFocus(activeService))
  }
  lines.push(SECURITY_LINE)

  // Анкета ПІСЛЯ SECURITY_LINE: правила безпеки вже прочитані,
  // тому спроба перебити їх із анкети не спрацює.
  const profileBlock = aiProfile
    ? buildProfileBlock(parseAiProfile(aiProfile))
    : null
  if (profileBlock) lines.push(profileBlock)

  lines.push(langBottom)
  return lines.join('\n')
}
