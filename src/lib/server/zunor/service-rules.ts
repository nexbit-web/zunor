import { SERVICES } from '$lib/categories/cleaning/presets'

export type ServiceKey = (typeof SERVICES)[number]['key']

interface ServiceRule {
  /** Крок 3 воронки: без цього заявки немає. */
  required: string
  /** Крок 5: що питати для ціни — скільки повідомлень і що в кожному. */
  price: string
  /** Що НЕ питати: це покаже фото або це не стосується послуги. */
  never: string
}

// ─── Правила по послугах ───
//
// Єдиний шаблон: required → price → never. Крок 5 описаний як ПЛАН
// повідомлень, а не перелік тем: модель, якій дали теми, складала з них
// стіну з 4–6 питань або губила половину (так губились площа й обсяг
// сміття — головне для ціни). Не більше 3 пунктів в одному повідомленні.
//
// Склад питань звірений прогоном діалогів (docs/zunor-test-dialogs.md):
// кожен пункт або змінює ціну, або змінює те, як майстер працює. Решту
// покаже фото або обговорять у чаті після вибору майстра. Тримай кожен
// блок коротким: що довший промпт, то легше модель губить мову й правила.

