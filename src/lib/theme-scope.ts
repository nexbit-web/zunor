// Де діє тема. Темна тема — налаштування кабінету: перемикач є лише в
// налаштуваннях, і вмикається вона тільки на `/dashboard/**`. Усе, що
// бачить людина до входу (лендинг, вхід і реєстрація, профілі майстрів,
// «Про нас»), — завжди світле, хоч би що лежало в її виборі.
//
// Те саме правило вмикає й світлу палітру кабінету (клас `in-app` на
// <html>, див. layout.css): лендинг лишається на своїй.
//
// Тому клас `dark` на <html> ставить не mode-watcher (йому передано
// порожній darkClassNames — він лише памʼятає вибір), а ми:
//  — до першого кадру — скрипт в app.html (та сама перевірка шляху);
//  — далі — ефект у кореневому лейауті (`isThemedPath` + `mode.current`).
// Міняєш правило — міняй обидва місця.

/** Шлях, на якому діє обрана тема (кабінет). */
export function isThemedPath(pathname: string): boolean {
  return pathname === '/dashboard' || pathname.startsWith('/dashboard/')
}
